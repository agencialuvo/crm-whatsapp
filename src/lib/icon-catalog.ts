export function isIconKey(value: unknown): value is IconKey {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(ICON_CATALOG, value);
}

/** El icono de una llave; una desconocida (o ausente) cae al de respaldo en vez de romper la pantalla. */
export function iconFor(key: string | null | undefined, fallback: IconKey = "store"): LucideIcon {
  return isIconKey(key) ? ICON_CATALOG[key] : ICON_CATALOG[fallback];
}
